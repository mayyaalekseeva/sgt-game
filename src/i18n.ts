export type Key = keyof typeof en
const dicts = { en, pt }

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s: string = dicts[lang][key] ?? key
  if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, String(vars[k]))
  return s
}
